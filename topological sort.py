def test_typical_dag():
    # Одевание:)
    graph = {
        "носки": ["ботинки"],
        "штаны": ["ботинки", "ремень"],
        "ремень": ["куртка"],
        "рубашка": ["ремень", "галстук"],
        "галстук": ["куртка"],
        "ботинки": [],
        "куртка": [],
    }
    for name, func in [("Кан", topological_sort_kahn),
                       ("DFS", topological_sort_dfs)]:
        order = func(graph)
        print("Типичный DAG,", name, ":", order)
        assert len(order) == 7
        assert is_valid_order(graph, order)


def test_simple_dag():
    graph = {1: [2, 3], 2: [4], 3: [4], 4: []}
    order = topological_sort(graph)
    print("Простой DAG:", order)
    assert is_valid_order(graph, order)


def test_cycle():
    graph = {"A": ["B"], "B": ["C"], "C": ["A"]}  # A -> B -> C -> A
    for name, func in [("Кан", topological_sort_kahn),
                       ("DFS", topological_sort_dfs)]:
        try:
            func(graph)
            print("ОШИБКА: цикл не обнаружен,", name)
            assert False
        except CycleError:
            print("Граф с циклом,", name, ": ошибка поймана — OK")


def test_self_loop():
    graph = {"A": ["A"]}  # петля тоже цикл
    try:
        topological_sort(graph)
        assert False
    except CycleError:
        print("Петля: ошибка поймана — OK")


