class CycleError(Exception):
    pass
# создаем новую ошибку, которую будем вызывать, если наткнемся на цикл. Топологическая сортировка применина
# только к ациклическим графам, это надо, чтобы при зацикливании оборвать программу, потому что для графов
# с циклом ответа физически не существует.

# Вспомогательная функция: собрать список ВСЕХ вершин графа.
# Некоторые вершины могут встречаться только справа (как "конец стрелки"),
# поэтому просто взять ключи словаря недостаточно.
def get_all_vertices(graph): # graph - словарь, ключ - откуда выходит стрелка(название вершины), и значение - список вершин, куда входят стрелки эти
    vertices = [] # список, в который потом будем добавлять названия вершин
    for v in graph: # обходим все ключи словаря
        if v not in vertices:
            vertices.append(v) # добавляем вершину в список, если ее еще там нет
        for u in graph[v]: # обходим все значения в рамках каждого ключа
            if u not in vertices:
                vertices.append(u) # добавляем, если нету, это будут тупиковые вершины, из которых не выходят стрелки
    return vertices # в итоге получаем список всех имеющихся вершин


def topological_sort_kahn(graph):
    vertices = get_all_vertices(graph)

    # 1. Считаем для каждой вершины, сколько стрелок В неё входит.
    in_degree = {} # словарь, ключ - название вершины, значение - входящая степень вершины(сколько степень в нее входит)
    for v in vertices: # проходимя по вершинам из списка всех вершин
        in_degree[v] = 0 # обнуляем переменную входящей степени
    for v in graph: # проходимся по вершинам в словаре всех вершин
        for u in graph[v]: # проходимся для каждой вершины по списку вершин, которые от нее зависят для каждой из них добавляем 1 в значение входящей степени
            in_degree[u] += 1

    # 2. Кладём в очередь все вершины, у которых входящих стрелок нет
    # (они ни от кого не зависят, их можно делать первыми).
    queue = [] # создаем очередь
    for v in vertices:
        if in_degree[v] == 0:
            queue.append(v) # добавляем туда вершины, которые не зависят ни от кого, то есть те, у которых входящая степень 0

    result = [] # список

    # 3. Берём вершину из очереди, добавляем в результат
    # и "стираем" её исходящие стрелки: у соседей входящая степень уменьшается.
    # Если у соседа она стала 0 — он теперь свободен, кладём в очередь.
    while len(queue) > 0: # двигаемся по элементам очереди, пока она не опустеет
        v = queue.pop(0) # вызываем 1 элемент из очереди в переменную v и удаляем его из очереди
        result.append(v) # добавляем элемент в список result
        for u in graph.get(v, []): # проходимся по списку вершин, которые зависели от выполненной вершины v
            in_degree[u] -= 1 # у каждой из них отнимаем 1 из числа входящей степени
            if in_degree[u] == 0:
                queue.append(u) # если вершина больше ни от кого не зависит, добавляем ее в очередь

    # 4. Проверка на цикл.
    # Вершины на цикле никогда не получат степень 0, значит в результат
    # попадут не все вершины.
    if len(result) != len(vertices): # в result в итоге должны попасть все вершины, поэтому сравниваем его длину и длину изначального списка вершин
        raise CycleError("в графе цикл")

    return result # список вершин в порядке их прохождения


def topological_sort_dfs(graph):
    vertices = get_all_vertices(graph) # список всех вершин
    # Цвета вершин:
    #   0 — белая (ещё не заходили)
    #   1 — серая (сейчас в процессе обработки, мы "внутри" неё)
    #   2 — чёрная (полностью обработана)
    color = {} # словарь, ключ - номер вершины, значение - цвет
    for v in vertices: # проходим по вершинам
        color[v] = 0 # помечаем в словаре каждую вершину как нетронутую

    # Сюда вершины записываются в порядке ВЫХОДА из них.
    exit_order = []

    def dfs(v): # функция, с помощью которой будем обрабатывать каждую вершину
        color[v] = 1  # зашли в вершину
        for u in graph.get(v, []): # смотрим все вершины, которые зависят от рассматриваемой
            if color[u] == 1:
                # если встречаем серую вершину = вернулись в ту, что ещё обрабатывается => это цикл
                raise CycleError("В графе есть цикл!")
            if color[u] == 0:
                dfs(u) # если встречаем белую вершину, то начинаем работать с ней
        color[v] = 2 # красим обработанную вершину в черный цвет
        exit_order.append(v)  # добавляем вершину в список с порядком выхода из вершин

    for v in vertices: # если остались непройденные вершины, то делаем с ними ту же функцию
        if color[v] == 0:
            dfs(v)

    # Вершина выходит ПОСЛЕ всех, на кого она указывает.
    # Значит, чем позже вышли — тем раньше должны стоять в ответе.
    # Поэтому разворачиваем список.
    exit_order.reverse()
    return exit_order # выводим список выхода в обратном порядке и возвращаем его как результат работы функции


# выбираем основную функцию, для которой будем проводить тесты
def topological_sort(graph):
    return topological_sort_kahn(graph)


def is_valid_order(graph, order):
    position = {} # словарь, ключ - вершина, значение - ее номер в списке order
    for i in range(len(order)):
        position[order[i]] = i # записыаем в словарь: ключ - вершина, значение - i итерация, то есть какой по порядку в order является эта вершина
    for v in graph:
        for u in graph[v]:
            if position[v] > position[u]: # сравниваем, что порядок заисящей вершины должен быть больше той, от которой она зависит, типо она прошла после нее
                return False
    return True


